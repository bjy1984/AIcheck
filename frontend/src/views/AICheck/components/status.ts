const normalizeStatus = (status?: string) => {
  const value = (status || '').trim().replace(/^AI\s+(预审中|审查中|复核中|处理中)$/, 'AI$1')
  return /^[A-Za-z0-9_\s-]*$/.test(value) ? value.toLowerCase().replace(/[\s-]+/g, '_') : value
}

export const getStatusTagType = (status?: string): StatusTagType => {
  const value = normalizeStatus(status)
  for (const [type, values] of Object.entries(states)) {
    if (values.has(value)) return type as StatusTagType
  }
  // Unknown contract values remain neutral. Do not guess success from prose.
  return 'info'
}

const tones: Record<StatusTagType, StatusTone> = {
  success: 'green',
  primary: 'blue',
  warning: 'orange',
  danger: 'red',
  info: 'gray'
}

const icons: Record<StatusTagType, string> = {
  success: 'vi-ep:circle-check',
  primary: 'vi-ep:refresh',
  warning: 'vi-ep:clock',
  danger: 'vi-ep:circle-close',
  info: 'vi-ep:minus'
}

export const getStatusTone = (status?: string): StatusTone => tones[getStatusTagType(status)]
export const getStatusIcon = (status?: string) => icons[getStatusTagType(status)]
export const getMetricClass = (tone?: string) => `metric-card metric-card--${tone || 'gray'}`
