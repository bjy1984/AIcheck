import { chromium, expect } from '@playwright/test'
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1280, height: 1100 } })
page.setDefaultTimeout(15000)
const errors = []
page.on('pageerror', error => errors.push(String(error)))
try {
  await page.goto('http://127.0.0.1:4393/e2e/lab-rules/documents.html')
  await page.getByRole('button', { name: '选择本次文件', exact: true }).click()
  await page.getByLabel('搜索文件名称、来源单位或类别').fill('LAB-PICK-01')
  await page.getByRole('button', { name: '搜索 / 刷新', exact: true }).click()
  await page.locator('.document-picker-row').filter({ hasText: 'LAB-PICK-01.txt' }).getByRole('button', { name: '版本', exact: true }).click()
  const old = page.locator('.version-row').filter({ hasText: 'historical.png' })
  await old.locator('.el-checkbox').click()
  await expect(old.getByRole('checkbox')).toBeChecked()
  await expect(page.locator('.version-row').filter({ hasText: 'EMPTY' }).getByRole('checkbox')).toBeDisabled()
  const responsePromise = page.waitForResponse(response => response.url().includes('versionId=VER-PICK-1-OLD'))
  await old.getByRole('button', { name: '预览此版本' }).click()
  const original = await responsePromise
  expect(original.headers()['content-type']).toContain('image/png')
  await expect(page.locator('.version-image')).toBeVisible()
  await expect.poll(() => page.locator('.version-image').evaluate(image => image.naturalWidth)).toBe(1)
  await page.getByRole('dialog', { name: 'historical.png · V0', exact: true }).locator('.el-dialog__headerbtn').click()
  await page.locator('.version-row').filter({ hasText: '当前版本' }).getByRole('button', { name: '预览此版本' }).click()
  await expect(page.getByText('所选版本原文不可用，未切换到其他版本。')).toBeVisible()
  await page.screenshot({ path: '../docs/lab/verification/browser/document-versions.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '返回文件选择', exact: true }).click()
  await expect(page.locator('.document-picker-chosen')).toContainText('historical.png · V0')
  await page.getByRole('button', { name: '保存本次选择', exact: true }).click()
  const selected = JSON.parse(await page.getByTestId('selection').textContent())
  expect(selected.versions).toEqual([{ documentId: 'DOC-PICK-1', versionId: 'VER-PICK-1-OLD', fileName: 'historical.png', versionNo: 'V0' }])
  await page.getByRole('button', { name: '本次文件 1 份', exact: true }).click()
  await expect(page.locator('.document-picker-chosen')).toContainText('historical.png · V0')
  expect(errors).toEqual([])
  console.log('PASS historical selection: exact version, image bytes rendered, missing body disabled, unavailable original error, retained selection')
} finally { await browser.close() }
