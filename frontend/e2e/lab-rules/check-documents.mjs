import { chromium, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1280, height: 1200 } })
page.setDefaultTimeout(15000)
const errors = []
page.on('pageerror', error => errors.push(String(error)))
try {
  await page.goto('http://127.0.0.1:4393/e2e/lab-rules/documents.html')
  await page.getByRole('button', { name: '选择本次文件', exact: true }).click()
  await page.getByLabel('搜索文件名称、来源单位或类别').fill('LAB-PICK')
  await page.getByRole('button', { name: '搜索 / 刷新', exact: true }).click()
  await page.locator('.document-picker-row').filter({ hasText: 'LAB-PICK-01.txt' }).getByRole('button', { name: '预览' }).click()
  await expect(page.getByText('此格式暂不支持内嵌预览，请在文件资料库查看。')).toBeVisible()
  await page.getByRole('dialog', { name: 'LAB-PICK-01.txt' }).locator('.el-dialog__headerbtn').click()
  await page.getByText('LAB-PICK-01.txt', { exact: true }).click()
  await page.locator('.btn-next').click()
  await page.getByText('LAB-PICK-21.txt', { exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'LAB-PICK-23.txt', exact: true })).toBeDisabled()
  await expect(page.locator('.document-picker-chosen')).toContainText('LAB-PICK-01.txt')
  await page.getByRole('button', { name: '保存本次选择', exact: true }).click()
  await expect(page.getByTestId('selection')).toContainText('VER-PICK-1')
  await expect(page.getByTestId('selection')).toContainText('VER-PICK-21')
  await expect(page.getByTestId('selection')).toContainText('gap_precheck')
  await page.getByRole('button', { name: '本次文件 2 份', exact: true }).click()
  await page.route('**/api/projects/*/documents?*', route => route.abort(), { times: 1 })
  await page.getByRole('button', { name: '搜索 / 刷新', exact: true }).click()
  await expect(page.getByText('文件列表加载失败，请重试。已选文件仍保留。')).toBeVisible()
  await expect(page.locator('.document-picker-chosen .el-tag')).toHaveCount(2)
  await page.locator('.document-picker-chosen .el-tag__close').first().click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('button', { name: '本次文件 2 份', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '本次文件 2 份', exact: true }).click()
  await page.getByLabel('搜索文件名称、来源单位或类别').fill('LAB-PICK')
  await page.getByRole('button', { name: '搜索 / 刷新', exact: true }).click()
  await page.getByRole('button', { name: '选择本页', exact: true }).click()
  await expect(page.locator('.document-picker-chosen .el-tag')).toHaveCount(21)
  await page.getByText('正式复核', { exact: true }).click()
  await expect(page.getByRole('radio', { name: '正式复核', exact: true })).toBeChecked()
  mkdirSync('../docs/lab/verification/browser', { recursive: true })
  await page.screenshot({ path: '../docs/lab/verification/browser/document-picker.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '保存本次选择', exact: true }).click()
  await expect(page.getByTestId('selection')).toContainText('formal')
  await page.getByRole('button', { name: '切换测试节点', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择本次文件', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '选择本次文件', exact: true }).click()
  await expect(page.getByRole('button', { name: '保存本次选择', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '恢复使用节点资料', exact: true }).click()
  await expect(page.getByTestId('selection')).toHaveText('null')
  if (errors.length) throw new Error(errors.join('\n'))
  console.log('PASS document selection: search, pagination, missing body, cancel, batch, mode, context reset, defaults')
} catch (error) {
  await page.screenshot({ path: '/tmp/aicheck-picker-failure.png', fullPage: true })
  console.error(errors)
  throw error
} finally { await browser.close() }
